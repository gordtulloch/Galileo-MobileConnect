"""Check design/tokens.json and write each platform's token file (S-DSN, docs/SDD.md 3.10, docs/android/SDD.md 3.8):
ios/App/Theme/Tokens.generated.swift and android/design/.../Tokens.kt.

    python scripts/gen_tokens.py           check, then write
    python scripts/gen_tokens.py --check   check, and exit 1 if either file is out of date

Fails if a listed pair of colours is below the contrast minimum (MAPP-LAY-040), or if any Night colour has green
or blue in it (MAPP-LAY-030).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "design" / "tokens.json"
OUT = ROOT / "ios" / "App" / "Theme" / "Tokens.generated.swift"
KOTLIN_OUT = ROOT / "android" / "design" / "src" / "main" / "kotlin" / "com" / "galileo" / "mobileconnect" / "design" / "Tokens.kt"


def rgb(text: str) -> tuple[int, int, int]:
    return int(text[1:3], 16), int(text[3:5], 16), int(text[5:7], 16)


def luminance(text: str) -> float:
    def linear(channel: int) -> float:
        c = channel / 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = rgb(text)
    return 0.2126 * linear(r) + 0.7152 * linear(g) + 0.0722 * linear(b)


def contrast(a: str, b: str) -> float:
    high, low = sorted((luminance(a), luminance(b)), reverse=True)
    return (high + 0.05) / (low + 0.05)


def faults(tokens: dict) -> list[str]:
    found = []
    for theme, colours in tokens["themes"].items():
        for fg, bg in tokens["contrast"]:
            ratio = contrast(colours[fg], colours[bg])
            if ratio < tokens["minimumContrast"]:
                found.append(f"{theme}: {fg} on {bg} is {ratio:.2f}:1")
    for name, value in tokens["themes"]["night"].items():
        _, green, blue = rgb(value)
        if green or blue:
            found.append(f"night: {name} {value} is not red only")
    return found


def swift(tokens: dict) -> str:
    names = list(tokens["themes"]["night"])
    lines = ["// Generated by scripts/gen_tokens.py from design/tokens.json. Do not edit.", "", "import SwiftUI", "",
             "struct ThemeTokens: Equatable {"]
    lines += [f"    let {name}: Color" for name in names]
    lines += ["}", "", "extension ThemeTokens {"]
    for theme, colours in tokens["themes"].items():
        lines.append(f"    static let {theme} = ThemeTokens(")
        parts = []
        for name in names:
            r, g, b = rgb(colours[name])
            parts.append(f"        {name}: Color(.sRGB, red: {r / 255:.4f}, green: {g / 255:.4f}, blue: {b / 255:.4f})")
        lines.append(",\n".join(parts))
        lines.append("    )")
    lines += ["}", "", "enum Layout {"]
    lines += [f"    static let {name}: CGFloat = {value}" for name, value in tokens["layout"].items()]
    lines += ["}", ""]
    return "\n".join(lines)


def kotlin(tokens: dict) -> str:
    names = list(tokens["themes"]["night"])
    newline = chr(10)
    lines = ["// Generated by scripts/gen_tokens.py from design/tokens.json. Do not edit.", "",
             "package com.galileo.mobileconnect.design", "",
             "/** Colours as 0xAARRGGBB, so this module needs no UI toolkit and its contrast check runs on the JVM. */",
             "data class ThemeTokens("]
    lines.append(("," + newline).join(f"    val {name}: Long" for name in names))
    lines += [") {", "    companion object {"]
    for theme, colours in tokens["themes"].items():
        lines.append(f"        val {theme} = ThemeTokens(")
        lines.append(("," + newline).join(f"            {name} = 0xFF{colours[name][1:].upper()}" for name in names))
        lines.append("        )")
    lines += ["    }", "}", "", "object Layout {"]
    lines += [f"    const val {name}: Float = {value}f" for name, value in tokens["layout"].items()]
    lines += ["}", ""]
    return newline.join(lines)


def main(argv: list[str]) -> int:
    tokens = json.loads(TOKENS.read_text(encoding="utf-8"))
    problems = faults(tokens)
    for problem in problems:
        print(problem)
    if problems:
        return 1
    outputs = [(OUT, swift(tokens)), (KOTLIN_OUT, kotlin(tokens))]
    if "--check" in argv:
        stale = [path for path, text in outputs if not path.exists() or path.read_text(encoding="utf-8") != text]
        if stale:
            print("OUT OF DATE: run python scripts/gen_tokens.py")
            return 1
        return 0
    for path, text in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline=chr(10))
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
