"""Check design/tokens.json and write ios/App/Theme/Tokens.generated.swift (S-DSN, docs/SDD.md 3.10).

    python scripts/gen_tokens.py           check, then write
    python scripts/gen_tokens.py --check   check, and exit 1 if the Swift file is out of date

Fails if a listed pair of colours is below the contrast minimum (MAPP-LAY-040), or if any Night colour has green
or blue in it (MAPP-LAY-030). The Kotlin output joins this when the Android app starts.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "design" / "tokens.json"
OUT = ROOT / "ios" / "App" / "Theme" / "Tokens.generated.swift"


def rgb(text: str) -> tuple[int, int, int]:
    return int(text[1:3], 16), int(text[3:5], 16), int(text[5:7], 16)


def luminance(text: str) -> float:
    def linear(channel: int) -> float:
        c = channel / 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = rgb(text)
    return 0.2126 * linear(r) + 0.7152 * linear(g) + 0.0722 * linear(b)


def contrast(a: str, b: str) -> float:
    high, low = sorted((luminance(a), luminance(b)), reverse=True)
    return (high + 0.05) / (low + 0.05)


def faults(tokens: dict) -> list[str]:
    found = []
    for theme, colours in tokens["themes"].items():
        for fg, bg in tokens["contrast"]:
            ratio = contrast(colours[fg], colours[bg])
            if ratio < tokens["minimumContrast"]:
                found.append(f"{theme}: {fg} on {bg} is {ratio:.2f}:1")
    for name, value in tokens["themes"]["night"].items():
        _, green, blue = rgb(value)
        if green or blue:
            found.append(f"night: {name} {value} is not red only")
    return found


def swift(tokens: dict) -> str:
    names = list(tokens["themes"]["night"])
    lines = ["// Generated by scripts/gen_tokens.py from design/tokens.json. Do not edit.", "", "import SwiftUI", "",
             "struct ThemeTokens: Equatable {"]
    lines += [f"    let {name}: Color" for name in names]
    lines += ["}", "", "extension ThemeTokens {"]
    for theme, colours in tokens["themes"].items():
        lines.append(f"    static let {theme} = ThemeTokens(")
        parts = []
        for name in names:
            r, g, b = rgb(colours[name])
            parts.append(f"        {name}: Color(.sRGB, red: {r / 255:.4f}, green: {g / 255:.4f}, blue: {b / 255:.4f})")
        lines.append(",\n".join(parts))
        lines.append("    )")
    lines += ["}", "", "enum Layout {"]
    lines += [f"    static let {name}: CGFloat = {value}" for name, value in tokens["layout"].items()]
    lines += ["}", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    tokens = json.loads(TOKENS.read_text(encoding="utf-8"))
    problems = faults(tokens)
    for problem in problems:
        print(problem)
    if problems:
        return 1
    text = swift(tokens)
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("OUT OF DATE: run python scripts/gen_tokens.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
